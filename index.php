<script>
// Contact form submission using Fetch API and SweetAlert2
document.addEventListener("DOMContentLoaded", () => {

  const form = document.getElementById("contact-form");

  // Check that the contact form exists before attaching the event
  if (form) {

    form.addEventListener("submit", function (e) {
      e.preventDefault();

      const formData = new FormData(form);

      // Show loading dialog
      Swal.fire({
        title: 'Sending...',
        text: 'Please wait while we submit your message.',
        allowOutsideClick: false,
        didOpen: () => {
          Swal.showLoading();
        }
      });

      fetch("contact.php", {
        method: "POST",
        body: formData,
      })
        .then((res) => {
          // Detect unsuccessful HTTP responses
          if (!res.ok) {
            throw new Error("Server returned an error. Please try again.");
          }

          return res.text();
        })
        .then((response) => {

          Swal.close();

          if (response.trim() === "success") {

            Swal.fire({
              icon: 'success',
              title: 'Message Sent!',
              text: 'Thank you for contacting us. We’ll respond shortly.',
            });

            form.reset();

          } else {

            Swal.fire({
              icon: 'error',
              title: 'Oops!',
              text: response || 'Unable to send your message. Please try again.',
            });

          }
        })
        .catch((err) => {

          Swal.close();

          Swal.fire({
            icon: 'error',
            title: 'Unexpected Error',
            text: 'Please try again later.',
          });

          console.error("Fetch error:", err);

        });

    });

  }
});
</script>

